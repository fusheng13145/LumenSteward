    /**
     * 随机抽取一题。
     *
     * @param random 随机源
     * @return 谜题
     */
    public static TurtleSoupPuzzle draw(Random random) {
        return PUZZLES.get(random.nextInt(PUZZLES.size()));
    }

    /**
     * 按编号取题（会话恢复时用）。
     *
     * @param id 谜题编号，如 {@code ts001}
     * @return 谜题；编号不存在返回 empty
     */
    public static Optional<TurtleSoupPuzzle> byId(String id) {
        if (id == null || id.isBlank()) {
            return Optional.empty();
        }
        return PUZZLES.stream().filter(p -> p.id().equals(id)).findFirst();
    }
